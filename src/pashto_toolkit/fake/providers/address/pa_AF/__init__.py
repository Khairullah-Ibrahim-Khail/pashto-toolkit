    # --- standard address contract, wired to the Afghan data above ---
    # Without these, street_name()/street_address()/postcode() would inherit
    # en_US templates and emit American addresses from an Afghanistan locale.
    city_formats = ("{{city}}",)
    street_name_formats = ("{{street}}",)
    street_address_formats = ("{{street}} {{building_number}}",)
    building_number_formats = ("#", "##", "###")
    postcode_formats = ("#####",)

    def street_name(self) -> str:
        """Standard formatter name for :meth:`street`."""
        return self.street()

    def street_address(self) -> str:
        return f"{self.street()} {self.building_number()}"

    def postcode(self) -> str:
        """Standard formatter name for :meth:`postalcode`."""
        return self.postalcode()

    def state(self) -> str:
        """Afghanistan's first-level divisions are provinces."""
        return self.province()

    def administrative_unit(self) -> str:
        return self.province()

    def current_country_code(self) -> str:
        return "AF"

    def province(self):
        return self.generator.random.choice(self.provinces)

    def city(self, province=None):
        if province is None:
            province = self.province()
        return self.cities.get(province, province)

    def district(self, province=None):
        if province is None:
            province = self.province()
        return self.generator.random.choice(self.districts.get(province, [province]))

    def street(self):
        return self.generator.random.choice(self.streets)

    def postalcode(self):
        return str(self.generator.random.randint(10000, 99999))

    def address(self):
        province = self.province()
        city = self.city(province)
        district = self.district(province)
        street = self.street()
        postal = self.postalcode()
        return f"{street}, {district} ولسوالی, {city} ښار, {province}, {postal}"
